-- RStudio URL
SHOW ENDPOINTS IN SERVICE RSTUDIO_SERVICE;

-- Status and logs
SELECT SYSTEM$GET_SERVICE_STATUS('RSTUDIO_SERVICE') AS SERVICE_STATUS;
SELECT SYSTEM$GET_SERVICE_LOGS('RSTUDIO_SERVICE', 0, 'rstudio', 100) AS SERVICE_LOGS;

-- Suspend (save credits)
ALTER SERVICE RSTUDIO_SERVICE SUSPEND;
ALTER COMPUTE POOL RSTUDIO_POOL SUSPEND;

-- Resume
ALTER COMPUTE POOL RSTUDIO_POOL RESUME;
ALTER SERVICE RSTUDIO_SERVICE RESUME;
